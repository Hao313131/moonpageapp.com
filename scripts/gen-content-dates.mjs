#!/usr/bin/env node
/**
 * Write lib/content-dates.ts — the real last-changed date for each page, read
 * out of git history.
 *
 * Why: the sitemap used to stamp every URL with the build time, so every
 * deploy told Google that all ~130 pages had changed. Google only leans on
 * `lastmod` while it stays consistently accurate, so a blanket build-time
 * stamp doesn't just fail to help, it burns the one signal that asks for a
 * recrawl of the pages that genuinely did change.
 *
 * Each route maps to the source files that actually produce its content. A
 * route is dated by the newest commit touching any of them; shared chrome
 * (Header, Footer, globals.css) is deliberately excluded, since a footer link
 * tweak is not a change to 130 pages.
 *
 * If git history isn't available — a shallow CI checkout, or a tarball — this
 * writes an empty map and the sitemap omits `lastmod` entirely. Omitting is
 * correct; guessing is what we're fixing.
 */

import { execFileSync } from "child_process";
import { writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const SITE_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const git = (args) =>
  execFileSync("git", args, { cwd: SITE_ROOT, encoding: "utf8" }).trim();

/** A shallow clone only knows one commit, so every path would report the same
 * bogus date. Better to emit nothing than to re-introduce the old lie. */
function hasFullHistory() {
  try {
    if (git(["rev-parse", "--is-shallow-repository"]) === "true") {
      console.warn(
        "[content-dates] Shallow clone — no real history. Emitting empty map " +
          "(sitemap will omit lastmod). Set fetch-depth: 0 in the workflow.",
      );
      return false;
    }
    return true;
  } catch {
    console.warn("[content-dates] git unavailable — emitting empty map.");
    return false;
  }
}

/** Newest commit date across the given paths, as YYYY-MM-DD. */
function lastChanged(paths) {
  const out = git(["log", "-1", "--format=%cI", "--", ...paths]);
  return out ? out.slice(0, 10) : "";
}

/** Story and collection pages are generated from one data file each, so they
 * share its date — a story edit does move all of them, but that's honest:
 * the file those pages are built from really did change. */
const STORY_SOURCES = ["lib/stories.ts", "app/stories"];
const COLLECTION_SOURCES = ["lib/collections.ts", "app/collections"];

/** Marketing/hub routes: the page itself, plus any data it renders. */
const ROUTE_SOURCES = {
  "": ["app/page.tsx", "components/home", "lib/site.ts"],
  "/bedtime-stories": ["app/bedtime-stories"],
  "/toddler-bedtime-stories": ["app/toddler-bedtime-stories"],
  "/preschool-bedtime-stories": ["app/preschool-bedtime-stories"],
  "/read-aloud-bedtime-stories": ["app/read-aloud-bedtime-stories"],
  "/bedtime-stories-by-age": ["app/bedtime-stories-by-age"],
  "/cozy-bedtime-stories": ["app/cozy-bedtime-stories"],
  "/lullaby-bedtime-stories": ["app/lullaby-bedtime-stories"],
  "/bedtime-stories-app": ["app/bedtime-stories-app"],
  "/picture-books-for-kids": ["app/picture-books-for-kids"],
  "/stories": STORY_SOURCES,
  "/collections": COLLECTION_SOURCES,
  "/faq": ["app/faq", "lib/faq.ts"],
  "/guides": ["app/guides", "lib/guides.ts"],
  "/privacy": ["app/privacy"],
  "/privacy-choices": ["app/privacy-choices"],
  "/terms": ["app/terms"],
  "/support": ["app/support"],
};

const full = hasFullHistory();
const routes = {};
let storyDate = "";
let collectionDate = "";

if (full) {
  for (const [route, paths] of Object.entries(ROUTE_SOURCES)) {
    const d = lastChanged(paths);
    if (d) routes[route] = d;
  }
  storyDate = lastChanged(STORY_SOURCES);
  collectionDate = lastChanged(COLLECTION_SOURCES);
}

const out = `/** Generated by scripts/gen-content-dates.mjs — do not edit by hand.
 *
 * Real last-changed dates from git, used for sitemap <lastmod>. Empty when the
 * build has no git history, in which case the sitemap omits lastmod rather
 * than claiming a date it can't support.
 */
export const ROUTE_DATES: Record<string, string> = ${JSON.stringify(routes, null, 2)};

/** Story and collection pages are generated from a single data file each. */
export const STORY_DATE = ${JSON.stringify(storyDate)};
export const COLLECTION_DATE = ${JSON.stringify(collectionDate)};
`;

writeFileSync(join(SITE_ROOT, "lib/content-dates.ts"), out);
console.log(
  `[content-dates] ${Object.keys(routes).length} routes dated` +
    (full ? "" : " (no git history — lastmod will be omitted)"),
);
