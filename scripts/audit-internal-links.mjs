/**
 * Internal-link audit over the exported site (`out/`).
 *
 * Why: on-page SEO was already mature, but nothing was measuring the shape of
 * the internal link graph. Running this found two live hubs
 * (`/goodnight-bedtime-stories`, `/bedtime-story-ideas`) with 2 and 6 inbound
 * links while every sibling hub had 161 — they had been left out of the footer
 * and the HTML site map. Both of those lists were hand-maintained, which is how
 * it happened silently.
 *
 * What it reports:
 *   1. Orphan pages — real pages with zero inbound internal links.
 *   2. Under-linked pages — well below the site median.
 *   3. Pages missing from the HTML site map (`/sitemap/`), which is the crawl
 *      surface that should reach everything.
 *
 * Run after a build: `npm run audit:links`. Exits non-zero only when a real
 * page has zero inbound links (a genuine defect), so it is safe to gate on.
 */
import { readFileSync, readdirSync, statSync } from "fs";
import { join, relative, dirname } from "path";
import { fileURLToPath } from "url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "out");

/** Pages that are deliberately not part of the link graph. */
const EXCLUDED = new Set([
  "/_not-found/",
  // The exported 404 page: Disallowed in robots.txt and reached by error only.
  "/404/",
  // Ad landing page: noindex, Disallowed, and intentionally link-isolated.
  "/get/",
  // Zero-second meta-refresh stubs generated by gen-legacy-redirects.mjs.
  "/stories/max-and-the-moonflowers/",
  "/stories/milos-little-boat/",
  "/stories/the-meadow-concert/",
  "/stories/the-tangled-kite/",
  "/collections/stories-about-honesty/",
  "/collections/stories-about-music/",
]);

/** Every index.html under out/. */
function walk(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, acc);
    else if (entry === "index.html") acc.push(full);
  }
  return acc;
}

/** "/cozy-bedtime-stories" — the canonical path of an exported page. */
function pagePath(file) {
  const rel = relative(OUT, file).replace(/index\.html$/, "");
  return `/${rel}`;
}

/** Normalise an href to a site path, or null when it is not an internal link. */
function toPath(href) {
  if (!href.startsWith("/")) return null;
  const bare = href.split("#")[0].split("?")[0];
  if (!bare) return null;
  // Leave real files alone (/feed.xml, /icon.png); slash the rest.
  if (!bare.endsWith("/") && !bare.includes(".")) return `${bare}/`;
  return bare;
}

const files = walk(OUT);
const pages = files.map(pagePath);
const inbound = new Map(pages.map((p) => [p, 0]));

for (const file of files) {
  const html = readFileSync(file, "utf8");
  const seen = new Set();
  for (const match of html.matchAll(/href="([^"]+)"/g)) {
    const target = toPath(match[1]);
    if (!target || target === pagePath(file) || seen.has(target)) continue;
    seen.add(target);
    if (inbound.has(target)) inbound.set(target, inbound.get(target) + 1);
  }
}

const real = pages.filter((p) => !EXCLUDED.has(p));
const counts = real.map((p) => inbound.get(p)).sort((a, b) => a - b);
const median = counts[Math.floor(counts.length / 2)];

console.log(`[audit-links] ${pages.length} exported pages, ${real.length} in the link graph`);
console.log(`[audit-links] inbound links — min ${counts[0]}, median ${median}, max ${counts.at(-1)}`);

const orphans = real.filter((p) => inbound.get(p) === 0);
console.log(`[audit-links] orphans (0 inbound): ${orphans.length}`);
for (const p of orphans) console.log(`    ORPHAN ${p}`);

const thin = real
  .filter((p) => inbound.get(p) > 0 && inbound.get(p) <= Math.floor(median / 2))
  .sort((a, b) => inbound.get(a) - inbound.get(b));
console.log(
  `[audit-links] thin (<= half the median, informational — deep pages live here): ${thin.length}`,
);
for (const p of thin) console.log(`    ${String(inbound.get(p)).padStart(3)}  ${p}`);

// The HTML site map should be able to reach every real page.
const sitemapFile = join(OUT, "sitemap", "index.html");
if (files.includes(sitemapFile)) {
  const html = readFileSync(sitemapFile, "utf8");
  const linked = new Set();
  for (const match of html.matchAll(/href="([^"]+)"/g)) {
    const target = toPath(match[1]);
    if (target) linked.add(target);
  }
  const missing = real.filter((p) => !linked.has(p));
  console.log(`[audit-links] not reachable from /sitemap/: ${missing.length}`);
  for (const p of missing) console.log(`    MISSING ${p}`);
} else {
  console.log("[audit-links] no out/sitemap/index.html — skipped the site map check");
}

if (orphans.length > 0) {
  console.error(`[audit-links] FAIL — ${orphans.length} real page(s) have no inbound internal link`);
  process.exit(1);
}
console.log("[audit-links] OK — every real page has at least one inbound internal link");
